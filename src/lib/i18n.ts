export const dictionaries: Record<Lang, Record<MessageKey, string>> = {
  pt,
  en,
};

export function isLang(value: unknown): value is Lang {
  return value === "pt" || value === "en";
}

const ERROR_CODES = new Set<string>([
  "BAD_REQUEST",
  "VALIDATION_ERROR",
  "UNAUTHENTICATED",
  "SESSION_EXPIRED",
  "FORBIDDEN",
  "NOT_FOUND",
  "CONFLICT",
  "QUEUE_CLOSED",
  "INVALID_STATE",
  "RATE_LIMITED",
  "PAYMENT_REQUIRED",
  "QUOTA_EXCEEDED",
  "SERVICE_UNAVAILABLE",
  "INTERNAL",
]);

export function isErrorCode(code: unknown): code is string {
  return typeof code === "string" && ERROR_CODES.has(code);
}

/** Looks up `key` and replaces `{placeholder}` occurrences from `params`. */
export function translate(
  lang: Lang,
  key: MessageKey,
  params?: Record<string, string | number>,
): string {
  const template = dictionaries[lang][key] ?? dictionaries[DEFAULT_LANG][key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match,
  );
}

/** BCP-47 tag used for `Intl` formatting. */
export function localeTag(lang: Lang): string {
  return lang === "en" ? "en-GB" : "pt-PT";
}
